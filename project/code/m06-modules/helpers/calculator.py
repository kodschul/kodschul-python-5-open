# Grundrechenarten


def add(a, b):
    """Gibt die Summe zurück."""
    return a + b


def subtract(a, b):
    """Gibt die Differenz a - b zurück."""
    return a - b


def multiply(a, b):
    """Gibt das Produkt zurück."""
    return a * b


def divide(a, b):
    """Gibt den Quotienten a / b zurück."""
    return a / b
